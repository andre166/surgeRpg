/** Icon of each attribute (stats, talents, auto distribution). */
export const STAT_ICONS = { hp: 'heart', atk: 'sword', def: 'shield', speed: 'boot', luck: 'clover' };

/** Green bar chart for the level. */
const LEVEL_COLORS = { w: '#a9f58a', l: '#5ccf4a', s: '#2f9a3a' };

export const LEVEL_ICON = { name: 'stats', colors: LEVEL_COLORS };

const cache = new Map();

function rects(name, colors) {
  const key = colors ? `${name}:${JSON.stringify(colors)}` : name;
  if (cache.has(key)) return cache.get(key);
  const grid = ICONS[name] ?? [];
  const out = [];
  grid.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const ch = row[x];
      let end = x + 1;
      while (end < row.length && row[end] === ch) end += 1;
      const fill = ch === '.' ? null : (colors?.[ch] ?? PALETTE[ch]);
      if (fill) out.push(<rect key={`${y}-${x}`} x={x} y={y} width={end - x} height={1} fill={fill} />);
      x = end;
    }
  });
  cache.set(key, out);
  return out;
}

export default function PixelIcon({ name, colors, size = 24, className = '' }) {
  return (
    <svg className={`pixel-icon ${className}`} viewBox="0 0 16 16" width={size} height={size} shapeRendering="crispEdges" aria-hidden="true">
      {rects(name, colors)}
    </svg>
  );
}

/** The hero's own pixel art at icon size (heroes without art get the warrior helm icon). */
export function HeroPortrait({ index, size = 24 }) {
  const url = heroArtUrl(index);
  if (!url) return <PixelIcon name="warrior" size={size} />;
  return <img className="hero-portrait" src={url} alt="" draggable={false} style={{ width: size, height: size, imageRendering: heroArtPixel(index) ? 'pixelated' : undefined }} />;
}
